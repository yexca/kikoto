// The line Kikoto puts at the start of lyrics written by speech recognition or
// translation, naming the models in the lyrics' own language. The wording
// matches the server's templates in backend/internal/llm/attribution.go;
// change them together.
const templates = [
  ["Lyrics translated by ", ""],
  ["Lyrics generated by ", ""],
  ["当前歌词由 ", " 翻译"],
  ["当前歌词由 ", " 生成"],
  ["目前歌詞由 ", " 翻譯"],
  ["目前歌詞由 ", " 生成"],
  ["この歌詞は ", " によって翻訳されました"],
  ["この歌詞は ", " によって生成されました"],
  ["현재 가사는 ", "(으)로 번역되었습니다"],
  ["현재 가사는 ", "(으)로 생성되었습니다"],
] as const;

/** Whether a lyrics line is the line naming the models that wrote the file. */
export function isLyricsAttribution(text: string) {
  const line = text.trim();
  return templates.some(
    ([prefix, suffix]) =>
      line.startsWith(prefix) && line.endsWith(suffix) && line.length > prefix.length + suffix.length,
  );
}
