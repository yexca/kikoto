package llm

import "testing"

func TestAttributionUsesLyricsLanguageAndNamesOnlyModels(t *testing.T) {
	for _, tc := range []struct{ language, asr, llm, want string }{
		{"zh-cn", "", "example-llm", "当前歌词由 example-llm 翻译"},
		{"zh-cn", "example-asr", "", "当前歌词由 example-asr 生成"},
		{"zh-cn", "example-asr", "example-llm", "当前歌词由 example-asr 生成，example-llm 翻译"},
		{"ja-jp", "", "example-llm", "この歌詞は example-llm によって翻訳されました"},
		{"", "example-asr", "", "Lyrics generated by example-asr"},
		{"en-us", "multi\nline-->model", "", "Lyrics generated by multi line->model"},
		{"zh-cn", "", "", ""},
	} {
		if got := Attribution(tc.language, tc.asr, tc.llm); got != tc.want {
			t.Errorf("Attribution(%q,%q,%q)=%q, want %q", tc.language, tc.asr, tc.llm, got, tc.want)
		}
	}
	if !IsAttribution("目前歌詞由 example-llm 翻譯") || IsAttribution("Example lyric line") {
		t.Fatal("attribution recognition")
	}
}

func TestAttributionPlacementPerFormat(t *testing.T) {
	line := Attribution("en-us", "", "example-llm")
	for _, tc := range []struct{ name, format, source, want string }{
		{"example.lrc", ".lrc", "[ar:Example]\n[00:01.20]one\n[00:03.00]two\n", "[ar:Example]\n[00:00.00]" + line + "\n[00:01.20]one\n[00:03.00]two\n"},
		{"example.vtt", ".vtt", "WEBVTT\n\n00:00:01.500 --> 00:00:02.000\none\n", "WEBVTT\n\n00:00:00.000 --> 00:00:01.500\n" + line + "\n\n00:00:01.500 --> 00:00:02.000\none\n"},
		// The first line starts at 0, so both show together until it ends.
		{"example.vtt", ".vtt", "WEBVTT\n\ncue-1\n00:00.000 --> 00:02.000\none\n", "WEBVTT\n\n00:00:00.000 --> 00:00:02.000\n" + line + "\n\ncue-1\n00:00.000 --> 00:02.000\none\n"},
		{"example.srt", ".srt", "1\n00:00:01,000 --> 00:00:02,000\none\n\n2\n00:00:03,000 --> 00:00:04,000\ntwo\n", "1\n00:00:00,000 --> 00:00:01,000\n" + line + "\n\n2\n00:00:01,000 --> 00:00:02,000\none\n\n3\n00:00:03,000 --> 00:00:04,000\ntwo\n"},
		{"example.ass", ".ass", "[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,one\n", "[Events]\nDialogue: 0,0:00:00.00,0:00:01.00,Default,,0,0,0,," + line + "\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,one\n"},
		{"example.txt", ".txt", "one\ntwo", line + "\none\ntwo"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, err := AddAttribution(tc.format, tc.source, line)
			if err != nil || got != tc.want {
				t.Fatalf("add=%q err=%v", got, err)
			}
			if stripped := StripAttribution(tc.name, got); stripped != tc.source {
				t.Fatalf("strip=%q", stripped)
			}
			// A translation source never sends the line, and keeps the
			// original line count for the review timeline.
			document, err := ParseLyrics(tc.name, got)
			if err != nil {
				t.Fatal(err)
			}
			for _, text := range document.Text() {
				if IsAttribution(text) {
					t.Fatalf("attribution sent: %q", text)
				}
			}
		})
	}
}

func TestStripAttributionKeepsOrdinaryFirstLine(t *testing.T) {
	source := "[00:00.00]Example opening\n[00:01.00]one\n"
	if got := StripAttribution("example.lrc", source); got != source {
		t.Fatalf("strip=%q", got)
	}
}
