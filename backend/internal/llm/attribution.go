package llm

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"unicode"
)

// A lyrics file Kikoto writes from speech recognition or translation opens
// with one line in the lyrics' own language naming the models that made it.
// The line is placed where each format shows it first, and it is recognized
// again by its wording, so a file read as a translation source loses it before
// its lines are sent and the new file gets a line of its own.

// attributionTemplates hold, per lyrics language, the line for a translation,
// a transcription, and a transcription that was then translated. %[1]s is the
// speech model and %[2]s the translation model. Languages outside the table
// use English.
var attributionTemplates = map[string][3]string{
	"en-us": {"Lyrics translated by %[2]s", "Lyrics generated by %[1]s", "Lyrics generated by %[1]s and translated by %[2]s"},
	"zh-cn": {"当前歌词由 %[2]s 翻译", "当前歌词由 %[1]s 生成", "当前歌词由 %[1]s 生成，%[2]s 翻译"},
	"zh-tw": {"目前歌詞由 %[2]s 翻譯", "目前歌詞由 %[1]s 生成", "目前歌詞由 %[1]s 生成，%[2]s 翻譯"},
	"ja-jp": {"この歌詞は %[2]s によって翻訳されました", "この歌詞は %[1]s によって生成されました", "この歌詞は %[1]s によって生成され、%[2]s によって翻訳されました"},
	"ko-kr": {"현재 가사는 %[2]s(으)로 번역되었습니다", "현재 가사는 %[1]s(으)로 생성되었습니다", "현재 가사는 %[1]s(으)로 생성되고 %[2]s(으)로 번역되었습니다"},
}

var attributionPatterns = func() []*regexp.Regexp {
	patterns := []*regexp.Regexp{}
	for _, templates := range attributionTemplates {
		for _, template := range templates {
			quoted := regexp.QuoteMeta(template)
			quoted = strings.ReplaceAll(quoted, regexp.QuoteMeta("%[1]s"), `.+?`)
			quoted = strings.ReplaceAll(quoted, regexp.QuoteMeta("%[2]s"), `.+?`)
			patterns = append(patterns, regexp.MustCompile(`^`+quoted+`$`))
		}
	}
	return patterns
}()

// attributionModel keeps a model name to one short line that cannot carry a
// timing marker.
func attributionModel(model string) string {
	model = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, model)
	model = strings.Join(strings.Fields(strings.ReplaceAll(model, "-->", "->")), " ")
	if runes := []rune(model); len(runes) > 128 {
		model = string(runes[:128])
	}
	return model
}

// Attribution is the line naming the models that wrote lyrics in language.
// An empty model name leaves its part out; with no model there is no line.
func Attribution(language, asrModel, llmModel string) string {
	asrModel, llmModel = attributionModel(asrModel), attributionModel(llmModel)
	templates, ok := attributionTemplates[language]
	if !ok {
		templates = attributionTemplates["en-us"]
	}
	switch {
	case asrModel != "" && llmModel != "":
		return fmt.Sprintf(templates[2], asrModel, llmModel)
	case asrModel != "":
		return fmt.Sprintf(templates[1], asrModel, llmModel)
	case llmModel != "":
		return fmt.Sprintf(templates[0], asrModel, llmModel)
	}
	return ""
}

// IsAttribution reports whether a lyrics line is an attribution line.
func IsAttribution(text string) bool {
	text = strings.TrimSpace(text)
	for _, pattern := range attributionPatterns {
		if pattern.MatchString(text) {
			return true
		}
	}
	return false
}

func lyricsNewline(text string) string {
	if strings.Contains(text, "\r\n") {
		return "\r\n"
	}
	return "\n"
}

func splitLyricsLines(text string) []string {
	return strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
}

// AddAttribution places line at the start of lyrics in format (a ParseLyrics
// format such as ".lrc"). Timed formats show it from 0 until the first line
// starts; when the first line starts at 0 both show together, the attribution
// above it.
func AddAttribution(format, text, line string) (string, error) {
	if line == "" {
		return text, nil
	}
	newline := lyricsNewline(text)
	lines := splitLyricsLines(text)
	switch format {
	case ".lrc":
		index := 0
		for i, value := range lines {
			if lrcTimestamp.MatchString(value) {
				index = i
				break
			}
		}
		lines = insertLine(lines, index, "[00:00.00]"+line)
	case ".vtt", ".srt":
		separator := "."
		if format == ".srt" {
			separator = ","
		}
		timing := -1
		for i, value := range lines {
			if cueTimestamp.MatchString(strings.TrimSpace(value)) {
				timing = i
				break
			}
		}
		if timing < 0 {
			return "", fmt.Errorf("lyrics have no cue")
		}
		start, end, ok := cueTimes(lines[timing])
		if !ok {
			return "", fmt.Errorf("lyrics have an invalid cue")
		}
		until := start
		if start == 0 {
			until = end
		}
		cue := []string{cueTime(0, separator) + " --> " + cueTime(until, separator), line, ""}
		index := timing
		if timing > 0 && strings.TrimSpace(lines[timing-1]) != "" {
			index = timing - 1
		}
		if format == ".srt" {
			lines = shiftSRTNumbers(lines, 1)
			cue = append([]string{"1"}, cue...)
		}
		lines = append(lines[:index], append(cue, lines[index:]...)...)
	case ".ass", ".ssa":
		index := -1
		for i, value := range lines {
			if strings.HasPrefix(strings.TrimSpace(value), "Dialogue:") {
				index = i
				break
			}
		}
		if index < 0 {
			return "", fmt.Errorf("lyrics have no dialogue")
		}
		parts := strings.SplitN(lines[index], ",", 10)
		if len(parts) != 10 {
			return "", fmt.Errorf("invalid ASS dialogue")
		}
		start, ok := assTime(parts[1])
		end, endOK := assTime(parts[2])
		if !ok || !endOK {
			return "", fmt.Errorf("invalid ASS dialogue timing")
		}
		until := start
		if start == 0 {
			until = end
		}
		parts[1], parts[2], parts[9] = formatASSTime(0), formatASSTime(until), line
		lines = insertLine(lines, index, strings.Join(parts, ","))
	case ".txt":
		lines = insertLine(lines, 0, line)
	default:
		return "", fmt.Errorf("unsupported lyrics format")
	}
	result := strings.Join(lines, newline)
	if len(result) > LyricsLimit {
		return "", fmt.Errorf("lyrics exceed the text limit")
	}
	return result, nil
}

// StripAttribution removes the attribution line AddAttribution placed, and
// returns the text unchanged when it has none. name decides the format as
// ParseLyrics does.
func StripAttribution(name, text string) string {
	format := lyricsFormat(name, splitLyricsLines(strings.TrimPrefix(text, "\ufeff")))
	newline := lyricsNewline(text)
	lines := splitLyricsLines(text)
	switch format {
	case ".lrc":
		for i, value := range lines {
			if prefix := lrcTimestamp.FindString(value); prefix != "" {
				if IsAttribution(strings.TrimPrefix(value, prefix)) {
					lines = append(lines[:i], lines[i+1:]...)
				}
				break
			}
		}
	case ".vtt", ".srt":
		for i, value := range lines {
			if !cueTimestamp.MatchString(strings.TrimSpace(value)) {
				continue
			}
			if i+1 >= len(lines) || !IsAttribution(lines[i+1]) || i+2 < len(lines) && strings.TrimSpace(lines[i+2]) != "" {
				break
			}
			from, to := i, i+2
			if i > 0 && strings.TrimSpace(lines[i-1]) != "" {
				from = i - 1
			}
			if to < len(lines) {
				to++
			}
			lines = append(lines[:from], lines[to:]...)
			if format == ".srt" {
				lines = shiftSRTNumbers(lines, -1)
			}
			break
		}
	case ".ass", ".ssa":
		for i, value := range lines {
			if strings.HasPrefix(strings.TrimSpace(value), "Dialogue:") {
				if parts := strings.SplitN(value, ",", 10); len(parts) == 10 && IsAttribution(parts[9]) {
					lines = append(lines[:i], lines[i+1:]...)
				}
				break
			}
		}
	case ".txt":
		for i, value := range lines {
			if strings.TrimSpace(strings.TrimPrefix(value, "\ufeff")) == "" {
				continue
			}
			if IsAttribution(strings.TrimPrefix(value, "\ufeff")) {
				lines = append(lines[:i], lines[i+1:]...)
			}
			break
		}
	default:
		return text
	}
	return strings.Join(lines, newline)
}

// lyricsFormat is the format ParseLyrics reads a file as: its extension, or
// for a .txt file the timed format its lines use.
func lyricsFormat(name string, lines []string) string {
	ext := strings.ToLower(name)
	if dot := strings.LastIndexByte(ext, '.'); dot >= 0 {
		ext = ext[dot:]
	} else {
		ext = ""
	}
	if ext == ".txt" {
		for _, line := range lines {
			if lrcTimestamp.MatchString(line) {
				return ".lrc"
			}
			if cueTimestamp.MatchString(strings.TrimSpace(line)) {
				return ".vtt"
			}
		}
	}
	return ext
}

func insertLine(lines []string, index int, line string) []string {
	return append(lines[:index], append([]string{line}, lines[index:]...)...)
}

// shiftSRTNumbers moves every numeric cue identifier by delta.
func shiftSRTNumbers(lines []string, delta int) []string {
	for i := 0; i+1 < len(lines); i++ {
		if !cueTimestamp.MatchString(strings.TrimSpace(lines[i+1])) {
			continue
		}
		if number, err := strconv.Atoi(strings.TrimSpace(lines[i])); err == nil {
			lines[i] = strconv.Itoa(max(1, number+delta))
		}
	}
	return lines
}

var cueTimePattern = regexp.MustCompile(`^(?:(\d{1,2}):)?(\d{2}):(\d{2})[.,](\d{3})$`)

func cueTimes(line string) (int64, int64, bool) {
	fields := strings.Fields(strings.TrimSpace(line))
	if len(fields) < 3 || fields[1] != "-->" {
		return 0, 0, false
	}
	start, ok := parseCueTime(fields[0])
	end, endOK := parseCueTime(fields[2])
	return start, end, ok && endOK
}

func parseCueTime(value string) (int64, bool) {
	match := cueTimePattern.FindStringSubmatch(value)
	if match == nil {
		return 0, false
	}
	var hours int64
	if match[1] != "" {
		hours, _ = strconv.ParseInt(match[1], 10, 64)
	}
	minutes, _ := strconv.ParseInt(match[2], 10, 64)
	seconds, _ := strconv.ParseInt(match[3], 10, 64)
	millis, _ := strconv.ParseInt(match[4], 10, 64)
	return hours*3_600_000 + minutes*60_000 + seconds*1000 + millis, true
}

func cueTime(ms int64, separator string) string {
	return fmt.Sprintf("%02d:%02d:%02d%s%03d", ms/3_600_000, ms/60_000%60, ms/1000%60, separator, ms%1000)
}

var assTimePattern = regexp.MustCompile(`^(\d+):(\d{2}):(\d{2})\.(\d{2})$`)

func assTime(value string) (int64, bool) {
	match := assTimePattern.FindStringSubmatch(strings.TrimSpace(value))
	if match == nil {
		return 0, false
	}
	hours, _ := strconv.ParseInt(match[1], 10, 64)
	minutes, _ := strconv.ParseInt(match[2], 10, 64)
	seconds, _ := strconv.ParseInt(match[3], 10, 64)
	centis, _ := strconv.ParseInt(match[4], 10, 64)
	return hours*3_600_000 + minutes*60_000 + seconds*1000 + centis*10, true
}

func formatASSTime(ms int64) string {
	return fmt.Sprintf("%d:%02d:%02d.%02d", ms/3_600_000, ms/60_000%60, ms/1000%60, ms%1000/10)
}
