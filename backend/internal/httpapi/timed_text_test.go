// timedTextFixture stores one work whose text files are read in a timed-text
// format; WebVTT is kept in a .txt file because library lyrics often are.
func timedTextFixture(t *testing.T, files map[string]string) *Server {
	t.Helper()
	dataRoot := t.TempDir()
	db := openMigratedTestDB(t)
	if _, err := db.Exec(`
		INSERT INTO file_source (id, code, display_name, source_type) VALUES (1, 'example_local', 'Example Local', 'local_folder');
		INSERT INTO work (id, primary_code, title) VALUES (1, 'RJ00000000', 'Example Work');
	`); err != nil {
		t.Fatal(err)
	}
	id := 0
	for name, content := range files {
		id++
		relPath := "Library/RJ00000000/" + name
		fullPath := filepath.Join(dataRoot, filepath.FromSlash(relPath))
		if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(fullPath, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		if _, err := db.Exec(`INSERT INTO media_item (id, work_id, kind, title, fingerprint) VALUES (?, 1, 'text', ?, ?)`, id, name, "synthetic-"+name); err != nil {
			t.Fatal(err)
		}
		if _, err := db.Exec(`INSERT INTO media_file_location (id, media_item_id, file_source_id, location_type, path, availability) VALUES (?, ?, 1, 'local', ?, 'available')`, id, id, relPath); err != nil {
			t.Fatal(err)
		}
	}
	return NewServer(db, config.Config{DataRoot: dataRoot})
}

func timedTextRequest(server *Server, id int, query string) *httptest.ResponseRecorder {
	request := httptest.NewRequest(http.MethodGet, "/api/media/"+strconv.Itoa(id)+"/text"+query, nil)
	request.SetPathValue("id", strconv.Itoa(id))
	response := httptest.NewRecorder()
	server.serveMediaText(response, request)
	return response
}

func TestMediaTextServesLyricsAndSubtitlesInTimedFormats(t *testing.T) {
	const credit = "Lyrics generated by example-model"
	files := map[string]string{
		"a-webvtt.txt": "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n" + credit + "\n\n00:00:03.000 --> 00:00:04.000\n<i>Example</i> line\n",
		"b-clip.srt":   "1\r\n00:00:01,500 --> 00:00:02,000\r\nExample &amp; line\r\n",
		"c-notes.txt":  "plain notes\nwithout timing\n",
	}
	server := timedTextFixture(t, files)
	ids := map[string]int{}
	for name := range files {
		var id int
		if err := server.db.QueryRow(`SELECT id FROM media_item WHERE title = ?`, name).Scan(&id); err != nil {
			t.Fatal(err)
		}
		ids[name] = id
	}

	lyrics := timedTextRequest(server, ids["a-webvtt.txt"], "?format=lyrics")
	var parsed struct {
		Timed bool `json:"timed"`
		Lines []struct {
			Time        float64 `json:"time"`
			Text        string  `json:"text"`
			Attribution bool    `json:"attribution"`
		} `json:"lines"`
		Text string `json:"text"`
	}
	if err := json.Unmarshal(lyrics.Body.Bytes(), &parsed); err != nil || lyrics.Code != http.StatusOK {
		t.Fatalf("lyrics = %d %s (%v)", lyrics.Code, lyrics.Body.String(), err)
	}
	if !parsed.Timed || len(parsed.Lines) != 2 ||
		parsed.Lines[0].Time != 1 || parsed.Lines[0].Text != credit || !parsed.Lines[0].Attribution ||
		parsed.Lines[1].Time != 3 || parsed.Lines[1].Text != "Example line" || parsed.Lines[1].Attribution {
		t.Fatalf("lyrics = %+v", parsed)
	}

	vtt := timedTextRequest(server, ids["b-clip.srt"], "?format=webvtt")
	if want := "WEBVTT\n\n00:00:01.500 --> 00:00:02.000\nExample &amp;amp; line\n"; vtt.Code != http.StatusOK ||
		vtt.Body.String() != want || !strings.HasPrefix(vtt.Header().Get("Content-Type"), "text/vtt") {
		t.Fatalf("webvtt = %d %q %q, want %q", vtt.Code, vtt.Header().Get("Content-Type"), vtt.Body.String(), want)
	}

	if response := timedTextRequest(server, ids["c-notes.txt"], "?format=webvtt"); response.Code != http.StatusUnprocessableEntity {
		t.Fatalf("a text with no cue = %d, want 422", response.Code)
	}
	plain := timedTextRequest(server, ids["c-notes.txt"], "?format=lyrics")
	if err := json.Unmarshal(plain.Body.Bytes(), &parsed); err != nil || plain.Code != http.StatusOK || parsed.Timed || len(parsed.Lines) != 0 || parsed.Text != files["c-notes.txt"] {
		t.Fatalf("plain text lyrics = %d %s", plain.Code, plain.Body.String())
	}
	if response := timedTextRequest(server, ids["c-notes.txt"], "?format=ass"); response.Code != http.StatusBadRequest {
		t.Fatalf("unknown format = %d, want 400", response.Code)
	}
	var raw struct {
		Content string `json:"content"`
	}
	if response := timedTextRequest(server, ids["c-notes.txt"], ""); json.Unmarshal(response.Body.Bytes(), &raw) != nil || raw.Content != files["c-notes.txt"] {
		t.Fatalf("no format must keep returning the text: %s", response.Body.String())
	}
}

func TestParseLyricsTextReadsTextTheClientHolds(t *testing.T) {
	server := &Server{}
	post := func(body string, signedIn bool) *httptest.ResponseRecorder {
		request := httptest.NewRequest(http.MethodPost, "/api/lyrics/parse", strings.NewReader(body))
		if signedIn {
			request = request.WithContext(context.WithValue(request.Context(), currentUserKey, currentUser{ID: 1}))
		}
		response := httptest.NewRecorder()
		server.parseLyricsText(response, request)
		return response
	}
	response := post(`{"text":"[ti:Example Title]\n[00:01.50]first\n[00:02.00]Lyrics translated by example-model"}`, true)
	var parsed timedLyricsResponse
	if err := json.Unmarshal(response.Body.Bytes(), &parsed); err != nil || response.Code != http.StatusOK {
		t.Fatalf("parse = %d %s", response.Code, response.Body.String())
	}
	if !parsed.Timed || len(parsed.Lines) != 2 || parsed.Lines[0].Time != 1.5 || parsed.Lines[0].Attribution ||
		!parsed.Lines[1].Attribution || len(parsed.Tags) != 1 || parsed.Tags[0].Key != "ti" {
		t.Fatalf("parsed = %+v", parsed)
	}
	if response := post(`{"text":"x"}`, false); response.Code != http.StatusUnauthorized {
		t.Fatalf("signed out = %d", response.Code)
	}
	if response := post(`{"text":"`+strings.Repeat("a", maxTextPreviewBytes+1)+`"}`, true); response.Code != http.StatusBadRequest {
		t.Fatalf("oversized text = %d, want 400", response.Code)
	}
	if response := post(`not json`, true); response.Code != http.StatusBadRequest {
		t.Fatalf("invalid body = %d, want 400", response.Code)
	}
}
